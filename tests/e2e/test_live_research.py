"""
LIVE research through the real browser (consumes Azure OpenAI tokens).
Opt-in only:  INSIGHTIQ_LIVE_RESEARCH=MSFT,NYKAA.NS  pytest -m e2e_live tests/e2e

For each company: open it, click Start Research, capture the new run ID from
the real POST /api/v1/jobs response, wait for the job, then verify in the
browser and through the API that a NEW report was generated by Azure OpenAI
(provider, served model, response IDs, token usage), is about the selected
company only, appears in Research History, and that the previous report is
still separately accessible. Evidence: docs/validation_evidence/live_research/.
"""
import json
import os
import re
import time
from datetime import datetime, timezone
from pathlib import Path

import httpx
import pytest

pytestmark = pytest.mark.e2e_live

PROJECT_ROOT = Path(__file__).resolve().parents[2]
BASE = os.getenv("INSIGHTIQ_E2E_URL", "http://127.0.0.1:5173")
API = os.getenv("INSIGHTIQ_TEST_BASE_URL", "http://127.0.0.1:8000")
EVIDENCE = PROJECT_ROOT / "docs" / "validation_evidence" / "live_research"
COMPANIES = [t.strip().upper() for t in os.getenv("INSIGHTIQ_LIVE_RESEARCH", "").split(",") if t.strip()]
JOB_TIMEOUT_SECONDS = int(os.getenv("INSIGHTIQ_LIVE_RESEARCH_TIMEOUT", "3600"))


def _key():
    return os.environ["API_ACCESS_KEY"]


def api(path):
    with httpx.Client(base_url=API, timeout=60, trust_env=False) as c:
        r = c.get(path, headers={"Authorization": f"Bearer {_key()}"})
        r.raise_for_status()
        return r.json()


def company_route(ticker):
    sec = ticker in api("/api/v1/companies")["supported_tickers"]
    if sec:
        return sec, f"/companies/{ticker}"
    market = "IN" if ticker.endswith((".NS", ".BO")) else "US"
    return sec, f"/markets/{market}/companies/{ticker}"


@pytest.mark.skipif(not COMPANIES, reason="set INSIGHTIQ_LIVE_RESEARCH to run live research")
@pytest.mark.parametrize("ticker", COMPANIES)
def test_start_research_generates_a_new_azure_report(ticker):
    from playwright.sync_api import sync_playwright

    EVIDENCE.mkdir(parents=True, exist_ok=True)
    before_runs = {r["run_id"] for r in api(f"/api/v1/research/runs?ticker={ticker}")["runs"]}
    previous = [r for r in api(f"/api/v1/research/runs?ticker={ticker}")["runs"] if r.get("report_available")]
    sec, route = company_route(ticker)
    record = {"ticker": ticker, "route": route, "started_at_utc": datetime.now(timezone.utc).isoformat()}

    with sync_playwright() as p:
        browser = p.chromium.launch(channel="msedge", headless=True)
        context = browser.new_context(viewport={"width": 1366, "height": 900})
        context.add_init_script("window.sessionStorage.setItem('insightiq-token', %s);" % json.dumps(_key()))
        page = context.new_page()
        page.on("dialog", lambda d: d.accept())
        page.goto(f"{BASE}/#{route}")
        page.wait_for_function("(t) => document.querySelector('h1')?.innerText.includes(t)", arg=ticker, timeout=120000)
        # Wait for content (the dev server websocket means the network never idles).
        page.wait_for_function("() => !document.querySelector('.skeleton')", timeout=180000)
        page.wait_for_timeout(1000)

        # SEC company pages: "Start research"; provider (market) pages: one
        # click on "Research this company" starts the run.
        name = "Start research" if sec else "Research this company"
        button = page.get_by_role("button", name=re.compile(rf"^\s*{name}\s*$"))
        with page.expect_response(lambda r: r.url.endswith("/api/v1/jobs") and r.request.method == "POST",
                                  timeout=60000) as posted:
            button.first.click()
        job = posted.value.json()
        run_id = job["run_id"]
        record["run_id"] = run_id
        assert posted.value.status == 202 and run_id not in before_runs

        deadline = time.time() + JOB_TIMEOUT_SECONDS
        status = None
        while time.time() < deadline:
            status = api(f"/api/v1/jobs/{run_id}")
            if status["status"] in ("completed", "failed"):
                break
            time.sleep(15)
        record["job"] = {k: status.get(k) for k in ("status", "error_code", "agent_statuses", "created_at_utc", "finished_at_utc")}
        assert status["status"] == "completed", status

        doc = api(f"/api/v1/companies/{ticker}/reports/{run_id}")
        report = doc["report"]
        generation = report["generation"]
        record["generation"] = {
            "provider": generation.get("provider"),
            "deployment": generation.get("deployment"),
            "models_served": generation.get("models_served"),
            "generated_at_utc": report.get("generated_at_utc"),
            "calls": [{k: c.get(k) for k in (
                "agent", "call", "status", "model", "response_id", "input_tokens", "output_tokens",
                "reasoning_tokens", "total_tokens", "elapsed_seconds", "provider_requests",
                "failure_reason", "fallback_reason", "selection_method")} for c in generation.get("calls", [])],
            "ai_analysis_status": generation.get("ai_analysis_status"),
        }
        record["source_freshness"] = report.get("source_freshness")
        assert report["run_id"] == run_id and report["ticker"] == ticker
        assert generation["provider"] == "azure_openai"
        assert all(m.startswith("gpt-5.4-pro") for m in generation["models_served"]), generation["models_served"]
        completed_calls = [c for c in generation["calls"] if c.get("status") == "completed"]
        assert completed_calls and all(c.get("response_id") for c in completed_calls)
        # Every cited news article belongs to the selected company.
        for article in report["news"]["approved_primary_articles"] + report["news"]["selected_articles"]:
            assert article["ticker"] == ticker
        record["news_articles_cited"] = [a.get("title") for a in report["news"]["approved_primary_articles"]]
        record["validation"] = {
            "financial_withheld": report["financial"]["analysis"].get("withheld"),
            "news_withheld": (report["news"].get("analysis") or {}).get("withheld"),
            "strategic_withheld": report["strategic"].get("withheld_analysis"),
        }

        # The browser renders the new report, labelled with its provider.
        page.goto(f"{BASE}/#{'/companies/' + ticker + '/reports/' + run_id if sec else route}")
        page.wait_for_function(
            "(id) => !document.querySelector('.skeleton') && (document.querySelector('.report')?.innerText || '').includes(id)",
            arg=run_id[:8], timeout=180000,
        )
        # The provider label sits in collapsed "details" panels: expand them first.
        page.evaluate("() => document.querySelectorAll('details').forEach((d) => { d.open = true; })")
        page.wait_for_timeout(500)
        assert page.locator("text=Azure OpenAI ·").count() > 0
        assert "Groq ·" not in page.inner_text("main")
        page.screenshot(path=str(EVIDENCE / f"{ticker}_{run_id[:8]}_report.png"), full_page=True)
        history = api(f"/api/v1/research/runs?ticker={ticker}")["runs"]
        assert any(r["run_id"] == run_id and r.get("report_available") for r in history)
        if previous:
            old = previous[-1]["run_id"]
            old_doc = api(f"/api/v1/companies/{ticker}/reports/{old}")
            assert old_doc["report"]["run_id"] == old != run_id
            record["previous_report_still_accessible"] = old
        # Executive summary (generated after the report) when it is ready.
        summary = None
        for _ in range(60):
            summary = api(f"/api/v1/companies/{ticker}/reports/{run_id}/executive-summary")
            if summary["status"] in ("completed", "unavailable"):
                break
            time.sleep(10)
        record["executive_summary"] = {
            "status": summary.get("status"),
            **{k: (summary.get("summary") or {}).get(k) for k in ("provider", "deployment", "model", "word_count", "reason")},
            "diagnostics": (summary.get("summary") or {}).get("diagnostics"),
        }
        browser.close()

    record["finished_at_utc"] = datetime.now(timezone.utc).isoformat()
    (EVIDENCE / f"{ticker}_{run_id}.json").write_text(json.dumps(record, indent=2, default=str), encoding="utf-8")


# ------------------------------------------------- verify completed live runs
# Re-checks runs that were already generated live (no new research, no tokens):
#   INSIGHTIQ_LIVE_RUN_IDS="MSFT:<run_id>,ITC.NS:<run_id>"  pytest -m e2e tests/e2e

RUN_IDS = [tuple(x.split(":", 1)) for x in os.getenv("INSIGHTIQ_LIVE_RUN_IDS", "").split(",") if ":" in x]


@pytest.mark.e2e
@pytest.mark.skipif(not RUN_IDS, reason="set INSIGHTIQ_LIVE_RUN_IDS to verify completed live runs")
@pytest.mark.parametrize("ticker,run_id", RUN_IDS)
def test_completed_live_run_is_genuine_and_rendered(ticker, run_id):
    from playwright.sync_api import sync_playwright

    EVIDENCE.mkdir(parents=True, exist_ok=True)
    job = api(f"/api/v1/jobs/{run_id}")
    assert job["status"] == "completed" and job["ticker"] == ticker
    doc = api(f"/api/v1/companies/{ticker}/reports/{run_id}")
    report, generation = doc["report"], doc["report"]["generation"]
    assert report["run_id"] == run_id and report["ticker"] == ticker
    assert generation["provider"] == "azure_openai"
    assert generation["models_served"] and all(m.startswith("gpt-5.4-pro") for m in generation["models_served"])
    calls = generation["calls"]
    completed = [c for c in calls if c.get("status") == "completed"]
    assert completed and all(c.get("response_id") for c in completed)
    for article in report["news"]["approved_primary_articles"] + report["news"]["selected_articles"]:
        assert article["ticker"] == ticker
    history = api(f"/api/v1/research/runs?ticker={ticker}")["runs"]
    assert any(r["run_id"] == run_id and r.get("report_available") for r in history)
    previous = [r["run_id"] for r in history if r.get("report_available") and r["run_id"] != run_id]
    if previous:
        assert api(f"/api/v1/companies/{ticker}/reports/{previous[-1]}")["report"]["run_id"] == previous[-1]
    summary = api(f"/api/v1/companies/{ticker}/reports/{run_id}/executive-summary")
    latest = api(f"/api/v1/research/runs?ticker={ticker}").get("latest_completed_run_id")
    if latest == run_id and not (summary.get("status") == "completed" and summary.get("is_current")):
        pytest.skip("opening this latest report would start a live AI generation (verify it deliberately)")

    sec, _ = company_route(ticker)
    with sync_playwright() as p:
        browser = p.chromium.launch(channel="msedge", headless=True)
        context = browser.new_context(viewport={"width": 1366, "height": 900})
        context.add_init_script("window.sessionStorage.setItem('insightiq-token', %s);" % json.dumps(_key()))
        page = context.new_page()
        page.goto(f"{BASE}/#/companies/{ticker}/reports/{run_id}")
        page.wait_for_function(
            "(id) => !document.querySelector('.skeleton') && (document.querySelector('.report')?.innerText || '').includes(id)",
            arg=run_id[:8], timeout=180000)
        page.evaluate("() => document.querySelectorAll('details').forEach((d) => { d.open = true; })")
        page.wait_for_timeout(500)
        assert page.locator("text=Azure OpenAI ·").count() > 0
        body = page.inner_text("main")
        assert "Groq ·" not in body and ticker in page.inner_text("h1")
        page.screenshot(path=str(EVIDENCE / f"{ticker}_{run_id[:8]}_rendered.png"), full_page=True)
        browser.close()

    record = {
        "ticker": ticker, "run_id": run_id, "verified_at_utc": datetime.now(timezone.utc).isoformat(),
        "job": {k: job.get(k) for k in ("status", "created_at_utc", "started_at_utc", "finished_at_utc", "agent_statuses")},
        "report_generated_at_utc": report.get("generated_at_utc"),
        "generation": {
            "provider": generation.get("provider"), "deployment": generation.get("deployment"),
            "models_served": generation.get("models_served"), "ai_analysis_status": generation.get("ai_analysis_status"),
            "calls": [{k: c.get(k) for k in ("agent", "call", "status", "model", "response_id", "input_tokens",
                                              "output_tokens", "reasoning_tokens", "total_tokens", "elapsed_seconds",
                                              "provider_requests", "failure_reason", "fallback_reason")} for c in calls],
        },
        "source_freshness": report.get("source_freshness"),
        "news_articles_cited": [a.get("title") for a in report["news"]["approved_primary_articles"]],
        "validation_withheld": {
            "financial": report["financial"]["analysis"].get("withheld"),
            "news": (report["news"].get("analysis") or {}).get("withheld"),
            "strategic": report["strategic"].get("withheld_analysis"),
        },
        "strategic_priorities": len(report["strategic"]["research_priorities"]),
        "previous_report_still_accessible": previous[-1] if previous else None,
        "executive_summary": {"status": summary.get("status"),
                              **{k: (summary.get("summary") or {}).get(k) for k in ("provider", "model", "word_count", "reason")},
                              "diagnostics": (summary.get("summary") or {}).get("diagnostics")},
        "browser": {"azure_label_rendered": True, "groq_label_absent": True, "route": f"/companies/{ticker}/reports/{run_id}"},
    }
    (EVIDENCE / f"{ticker}_{run_id}.json").write_text(json.dumps(record, indent=2, default=str), encoding="utf-8")
