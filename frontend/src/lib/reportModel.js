export function modelLabel(name, spec) {
  if (spec?.order && spec?.seasonal_order) {
    const [p, d, q] = spec.order;
    const [P, D, Q, s] = spec.seasonal_order;
    return `SARIMAX (${p},${d},${q})(${P},${D},${Q})${s ? `[${s}]` : ""}`;
  }
  return MODEL_LABELS[name] || name || "Unknown model";
}

const list = (value) => (Array.isArray(value) ? value : []);

function statementFor(evidenceId, statements) {
  return list(statements).find((s) => typeof s === "string" && s.includes(evidenceId)) || null;
}

/** Find computed QoQ / YoY for a claim in the company's stored series. */
export function comparisonFor(company, metric, periodEnd) {
  const series = company?.financials?.[metric];
  if (!Array.isArray(series)) return null;
  const index = series.findIndex((row) => row.period_end === periodEnd);
  if (index < 0) return null;
  const row = series[index];
  const byEnd = Object.fromEntries(series.map((r) => [r.period_end, r]));
  return {
    row,
    qoq: row.qoq_change_pct,
    qoqPrev: row.qoq_basis ? byEnd[row.qoq_basis] : null,
    yoy: row.yoy_change_pct,
    yoyPrev: row.yoy_basis ? byEnd[row.yoy_basis] : null,
  };
}

