export function modelLabel(name, spec) {
  if (spec?.order && spec?.seasonal_order) {
    const [p, d, q] = spec.order;
    const [P, D, Q, s] = spec.seasonal_order;
    return `SARIMAX (${p},${d},${q})(${P},${D},${Q})${s ? `[${s}]` : ""}`;
  }
  return MODEL_LABELS[name] || name || "Unknown model";
}

const list = (value) => (Array.isArray(value) ? value : []);

function statementFor(evidenceId, statements) {
  return list(statements).find((s) => typeof s === "string" && s.includes(evidenceId)) || null;
}

/** Find computed QoQ / YoY for a claim in the company's stored series. */
export function comparisonFor(company, metric, periodEnd) {
  const series = company?.financials?.[metric];
  if (!Array.isArray(series)) return null;
  const index = series.findIndex((row) => row.period_end === periodEnd);
  if (index < 0) return null;
  const row = series[index];
  const byEnd = Object.fromEntries(series.map((r) => [r.period_end, r]));
  return {
    row,
    qoq: row.qoq_change_pct,
    qoqPrev: row.qoq_basis ? byEnd[row.qoq_basis] : null,
    yoy: row.yoy_change_pct,
    yoyPrev: row.yoy_basis ? byEnd[row.yoy_basis] : null,
  };
}

export function buildReportModel(report, company) {
  if (!report || typeof report !== "object") return null;

  const financial = report.financial || {};
  const verified = financial.verified_claims || {};
  const news = report.news || {};
  const strategic = report.strategic || {};

  const claims = list(verified.verified_claims).map((claim) => ({
    ...claim,
    metricLabel: METRIC_LABELS[claim.metric] || claim.metric,
    period: periodRange(claim.period_start, claim.period_end),
    statement: statementFor(claim.evidence_id, verified.verified_statements),
    methodText: METHOD_TEXT[claim.normalization_method] || claim.normalization_method,
    comparison: comparisonFor(company, claim.metric, claim.period_end),
  }));

  const forecasts = Object.entries(financial.forecasts || {}).map(([metric, item]) => ({
    metric,
    metricLabel: METRIC_LABELS[metric] || metric,
    ...item,
    quality: (financial.forecast_quality || {})[metric] || null,
  }));

  const primaryIds = new Set(list(news.approved_primary_articles).map((a) => a.evidence_id));
  const articles = list(news.approved_primary_articles).map((a) => ({ ...a, primary: true }));
  const contextual = list(news.contextual_articles).filter((a) => !primaryIds.has(a.evidence_id));

  const priorities = list(strategic.research_priorities).map((p) => {
    const theme = THEMES[p.theme] || { title: p.theme, about: null };
    const source = p.source_metadata || {};
    return {
      ...p,
      title: theme.title,
      about: theme.about,
      isFinancial: source.kind === "verified_sec_financial_fact",
      source,
    };
  });

  return {
    runId: report.run_id,
    ticker: report.ticker,
    generatedAt: report.generated_at_utc,
    elapsed: report.total_elapsed_seconds,
    agentStatuses: report.agent_statuses || {},
    agentTimings: report.agent_timings_seconds || {},
    limitations: list(report.limitations),
    financial: {
      claims,
      forecasts,
      model: verified.model,
      diagnostics: verified.diagnostics || financial.groq_diagnostics || null,
      limitations: list(verified.limitations),
      disclosures: list(financial.disclosures),
    },
    news: {
      articles,
      contextual,
      themes: news.repeated_event_themes || {},
      diagnostics: news.groq_diagnostics || null,
      disclosures: list(news.disclosures),
    },
    strategic: {
      status: strategic.status,
      priorities,
      sourceEvidence: list(strategic.source_evidence),
      diagnostics: strategic.groq_diagnostics || null,
      disclosures: list(strategic.disclosures),
    },
  };
}
