/* ------------------------------------------------------------------ viewer */

export function ReportViewer({ token, doc, company, isLatest, inDatabase, onSummary }) {
  const model = useMemo(() => buildReportModel(doc.report, company), [doc.report, company]);
  if (!model) return <Notice tone="error">This saved report could not be read.</Notice>;

  const sections = [
    { id: "summary", label: "Summary", icon: Sparkles },
    { id: "financial", label: "Financial", icon: Landmark },
    { id: "news", label: "News", icon: Newspaper },
    { id: "strategic", label: "Strategic", icon: BrainCircuit },
    { id: "limitations", label: "Limitations", icon: FileText },
  ];

  return (
    <div className="report">
      <div className="report-head card">
        <div className="report-head-main">
          <p className="eyebrow">Research report</p>
          <h2 className="report-title">
            {model.ticker} research report · {formatDateTime(model.generatedAt)}
          </h2>
          <div className="badge-row">
            <StatusBadge status="completed" label="Completed" />
            {isLatest ? <Badge tone="info">Latest report</Badge> : <Badge tone="neutral">Earlier report</Badge>}
            <Badge tone="neutral">Run {shortId(model.runId)}</Badge>
            {model.elapsed !== undefined && <Badge tone="neutral">Ran in {formatSeconds(model.elapsed)}</Badge>}
            {inDatabase === false && (
              <Badge tone="warning" title="The job record is missing from the runtime database; this report was loaded from its original saved file.">
                Loaded from saved file
              </Badge>
            )}
          </div>
        </div>
        <dl className="agent-timings">
          {["financial", "news", "strategic"].map((agent) => (
            <div key={agent}>
              <dt>{humanize(agent)} Agent</dt>
              <dd>
                <StatusBadge status={model.agentStatuses[agent]} />
                <span className="muted small">{formatSeconds(model.agentTimings[agent])}</span>
              </dd>
            </div>
          ))}
        </dl>
        <nav className="report-nav" aria-label="Report sections">
          {sections.map((s) => (
            <a key={s.id} href={`#${s.id}`} onClick={(e) => {
              e.preventDefault();
              document.getElementById(s.id)?.scrollIntoView({ behavior: "smooth", block: "start" });
            }}>
              <s.icon size={14} aria-hidden="true" /> {s.label}
            </a>
          ))}
        </nav>
      </div>

      <ExecutiveSummary token={token} model={model} summary={doc.summary} onSummary={onSummary} />
      <FinancialSection model={model} />
      <NewsSection model={model} />
      <StrategicSection model={model} />

      <Card id="limitations" eyebrow="E · Evidence and limitations" title="Report limitations">
        <ul className="plain-list">
          {model.limitations.map((text) => (
            <li key={text}>{text}</li>
          ))}
        </ul>
        <EvidencePanel
          label="Full report data lineage"
          rows={[
            ["Run ID", model.runId],
            ["Company", model.ticker],
            ["Generated (UTC)", model.generatedAt],
            ["Financial evidence IDs", model.financial.claims.map((c) => c.evidence_id)],
            ["News evidence IDs", model.news.articles.map((a) => a.evidence_id)],
            ["Strategic evidence IDs", model.strategic.priorities.map((p) => p.evidence_id)],
            ["Report file", `reports/research_runs/${model.runId}.json`],
          ]}
        />
      </Card>
    </div>
  );
}

