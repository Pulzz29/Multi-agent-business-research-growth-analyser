-- Durable report files in Azure Blob Storage (additive). One row per immutable
-- blob: a file is "saved" only after its bytes were read back and the SHA-256
-- matched; failed uploads keep a record (attempts, last error) for recovery.
CREATE TABLE IF NOT EXISTS report_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blob_name TEXT COLLATE "C" NOT NULL UNIQUE,
    container TEXT COLLATE "C" NOT NULL,
    kind TEXT COLLATE "C" NOT NULL CHECK (kind IN ('research_pdf', 'sector_pdf', 'sector_docx')),
    ticker TEXT COLLATE "C",
    run_id TEXT COLLATE "C",
    comparison_id TEXT COLLATE "C",
    summary_version TEXT COLLATE "C",
    file_name TEXT COLLATE "C" NOT NULL,
    content_type TEXT COLLATE "C" NOT NULL,
    generated_at_utc TEXT COLLATE "C",
    sha256 TEXT COLLATE "C",
    size_bytes BIGINT,
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('saved', 'failed')),
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error TEXT COLLATE "C",
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_report_files_run ON report_files(run_id);
CREATE INDEX IF NOT EXISTS ix_report_files_comparison ON report_files(comparison_id);
