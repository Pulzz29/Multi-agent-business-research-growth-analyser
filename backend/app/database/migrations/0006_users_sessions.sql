-- Email/password accounts and server-side sessions (additive).
-- Passwords are stored only as salted scrypt hashes; session and CSRF tokens
-- only as SHA-256 hashes. Accounts are provisioned by scripts/provision_users.py.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT COLLATE "C" NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND position('@' in email) > 1),
    password_hash TEXT COLLATE "C" NOT NULL CHECK (password_hash LIKE 'scrypt$%'),
    status TEXT COLLATE "C" NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    last_login_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS user_sessions (
    token_sha256 TEXT COLLATE "C" PRIMARY KEY CHECK (length(token_sha256) = 64),
    user_id BIGINT NOT NULL REFERENCES users(id),
    csrf_sha256 TEXT COLLATE "C" NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    idle_expires_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_user_sessions_user ON user_sessions(user_id);
CREATE INDEX IF NOT EXISTS ix_user_sessions_expires ON user_sessions(expires_at);
