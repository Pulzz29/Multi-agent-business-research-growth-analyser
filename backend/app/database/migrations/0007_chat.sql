-- Company-research chatbot: conversations and messages per signed-in user (additive).
-- Every query filters on user_id; a conversation is never readable by another user.
CREATE TABLE IF NOT EXISTS chat_conversations (
    id TEXT COLLATE "C" PRIMARY KEY CHECK (length(id) = 36),
    user_id BIGINT NOT NULL REFERENCES users(id),
    ticker TEXT COLLATE "C",
    title TEXT COLLATE "C" NOT NULL DEFAULT 'New chat',
    pending_action_json TEXT COLLATE "C",
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_chat_conversations_user ON chat_conversations(user_id, updated_at);

CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id TEXT COLLATE "C" NOT NULL REFERENCES chat_conversations(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role TEXT COLLATE "C" NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL CHECK (length(content) <= 4000),
    ticker TEXT COLLATE "C",
    intent TEXT COLLATE "C",
    payload_json TEXT NOT NULL DEFAULT '{}',
    trace_id TEXT COLLATE "C",
    input_tokens BIGINT,
    output_tokens BIGINT,
    latency_ms DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_chat_messages_conversation ON chat_messages(conversation_id, id);
