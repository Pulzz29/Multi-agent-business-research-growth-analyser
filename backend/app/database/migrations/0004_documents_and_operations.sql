-- JSON documents (saved research reports and their summary/insight sidecars,
-- research-job journals, forecast caches), keyed by their path relative to
-- the project root. Every read verifies sha256.
CREATE TABLE IF NOT EXISTS stored_documents (
    path TEXT COLLATE "C" PRIMARY KEY,
    content TEXT NOT NULL,
    sha256 TEXT NOT NULL CHECK (length(sha256) = 64),
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- Correlated spans for API requests, database calls, calculations,
-- forecasting, agents, model calls, validation and PDF rendering.
CREATE TABLE IF NOT EXISTS telemetry_spans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id TEXT COLLATE "C" NOT NULL,
    span_id TEXT COLLATE "C" NOT NULL,
    parent_span_id TEXT COLLATE "C",
    run_id TEXT COLLATE "C",
    kind TEXT COLLATE "C" NOT NULL,
    name TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    duration_ms DOUBLE PRECISION NOT NULL,
    input_tokens BIGINT,
    output_tokens BIGINT,
    attributes_json TEXT COLLATE "C" NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS ix_telemetry_spans_trace ON telemetry_spans(trace_id, id);
CREATE INDEX IF NOT EXISTS ix_telemetry_spans_kind_time ON telemetry_spans(kind, started_at);
CREATE INDEX IF NOT EXISTS ix_telemetry_spans_run ON telemetry_spans(run_id);

-- Persistent alerts (one open alert per rule; repeated firing increments it).
CREATE TABLE IF NOT EXISTS operational_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule TEXT COLLATE "C" NOT NULL,
    severity TEXT COLLATE "C" NOT NULL CHECK (severity IN ('info', 'warning', 'critical')),
    message TEXT COLLATE "C" NOT NULL,
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    occurrences BIGINT NOT NULL DEFAULT 1,
    resolved_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_operational_alerts_open ON operational_alerts(rule) WHERE resolved_at IS NULL;

-- Simplified audit trail of state-changing actions (no request bodies or secrets).
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL,
    action TEXT COLLATE "C" NOT NULL,
    target TEXT COLLATE "C",
    outcome TEXT COLLATE "C" NOT NULL,
    trace_id TEXT COLLATE "C",
    client_hash TEXT COLLATE "C",
    details_json TEXT COLLATE "C" NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS ix_audit_events_time ON audit_events(occurred_at);

-- Database backups taken by scripts/backup_postgres.py and their verification.
CREATE TABLE IF NOT EXISTS backup_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    file_name TEXT COLLATE "C",
    size_bytes BIGINT,
    sha256 TEXT COLLATE "C",
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('running', 'succeeded', 'failed')),
    restore_verified BOOLEAN NOT NULL DEFAULT FALSE,
    verification_json TEXT COLLATE "C",
    error TEXT COLLATE "C"
);
