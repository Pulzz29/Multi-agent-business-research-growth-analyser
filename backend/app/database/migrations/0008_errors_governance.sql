-- Sanitised error records and AI governance records (additive).
-- No secrets, prompts or raw provider payloads are stored: messages and stack
-- traces are redacted and truncated; prompts are referenced by SHA-256 only.
CREATE TABLE IF NOT EXISTS error_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint TEXT COLLATE "C" NOT NULL UNIQUE,      -- one row per error occurrence chain (no duplicates)
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    occurrences BIGINT NOT NULL DEFAULT 1,
    severity TEXT COLLATE "C" NOT NULL CHECK (severity IN ('info', 'warning', 'error', 'critical')),
    stage TEXT COLLATE "C" NOT NULL,
    component TEXT COLLATE "C",                         -- agent / provider / service
    run_id TEXT COLLATE "C",
    conversation_id TEXT COLLATE "C",
    trace_id TEXT COLLATE "C",
    ticker TEXT COLLATE "C",
    error_type TEXT COLLATE "C" NOT NULL,
    message TEXT NOT NULL,                              -- sanitised
    stack_trace TEXT,                                   -- sanitised, project-relative
    retries INTEGER,
    duration_ms DOUBLE PRECISION,
    final_status TEXT COLLATE "C" NOT NULL DEFAULT 'failed'
);
CREATE INDEX IF NOT EXISTS ix_error_events_time ON error_events(last_seen_at);
CREATE INDEX IF NOT EXISTS ix_error_events_run ON error_events(run_id);

CREATE TABLE IF NOT EXISTS ai_governance_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL,
    component TEXT COLLATE "C" NOT NULL,                -- financial / news / strategic / summary / chatbot / research_report
    call_name TEXT COLLATE "C",
    outcome TEXT COLLATE "C" NOT NULL CHECK (outcome IN ('success', 'partial', 'rejected', 'failed', 'blocked')),
    run_id TEXT COLLATE "C",
    conversation_id TEXT COLLATE "C",
    trace_id TEXT COLLATE "C",
    ticker TEXT COLLATE "C",
    provider TEXT COLLATE "C",
    model TEXT COLLATE "C",
    prompt_sha256 TEXT COLLATE "C",
    guardrail_version TEXT COLLATE "C",
    validation_rejections INTEGER NOT NULL DEFAULT 0,
    violations_json TEXT NOT NULL DEFAULT '[]',
    evidence_json TEXT NOT NULL DEFAULT '{}'           -- provenance: evidence ids/sources and input SHA-256
);
CREATE INDEX IF NOT EXISTS ix_ai_governance_time ON ai_governance_events(occurred_at);
CREATE INDEX IF NOT EXISTS ix_ai_governance_component ON ai_governance_events(component, outcome);
