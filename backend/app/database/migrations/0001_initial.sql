-- InsightIQ schema on PostgreSQL: the 21 tables of the SQLite database with
-- the same columns, keys, unique constraints, foreign keys, CHECKs and indexes.
-- Timestamps and JSON stay TEXT (UTC ISO-8601 strings / JSON text), exactly as
-- the application reads and writes them; SQLite AUTOINCREMENT ids become
-- identity columns.

CREATE TABLE companies (
    ticker TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    cik TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE sec_facts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_ticker TEXT NOT NULL REFERENCES companies(ticker),
    source_key TEXT NOT NULL UNIQUE,
    taxonomy TEXT NOT NULL,
    concept TEXT NOT NULL,
    unit TEXT NOT NULL,
    value_text TEXT NOT NULL,
    period_start TEXT,
    period_end TEXT NOT NULL,
    fiscal_year BIGINT,
    fiscal_period TEXT,
    form TEXT,
    accession TEXT,
    filed_at TEXT,
    sec_frame TEXT,
    source_url TEXT,
    retrieved_at TEXT NOT NULL
);
CREATE INDEX ix_sec_facts_company_period ON sec_facts(company_ticker, concept, period_end);

CREATE TABLE news_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_ticker TEXT NOT NULL REFERENCES companies(ticker),
    provider TEXT NOT NULL,
    provider_article_id TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    article_url TEXT,
    source_name TEXT,
    published_at TEXT,
    retrieved_at TEXT NOT NULL,
    relevance_score DOUBLE PRECISION,
    relevance_reason TEXT,
    raw_metadata_json TEXT,
    UNIQUE (provider, provider_article_id, company_ticker)
);
CREATE INDEX ix_news_company_date ON news_articles(company_ticker, published_at);

CREATE TABLE source_refreshes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_ticker TEXT NOT NULL REFERENCES companies(ticker),
    source TEXT NOT NULL,
    started_at TEXT NOT NULL,
    completed_at TEXT,
    status TEXT NOT NULL,
    records_fetched BIGINT NOT NULL DEFAULT 0,
    records_inserted BIGINT NOT NULL DEFAULT 0,
    error_category TEXT,
    error_message TEXT
);
CREATE INDEX ix_source_refreshes_company_source ON source_refreshes(company_ticker, source, started_at);

CREATE TABLE research_jobs (
    job_id TEXT PRIMARY KEY,
    ticker TEXT NOT NULL REFERENCES companies(ticker),
    status TEXT NOT NULL CHECK (status IN ('queued', 'running', 'completed', 'partial_failure', 'failed')),
    request_json TEXT NOT NULL,
    created_at TEXT NOT NULL,
    started_at TEXT,
    completed_at TEXT,
    error_category TEXT,
    error_message TEXT
);
CREATE INDEX ix_jobs_ticker_created ON research_jobs(ticker, created_at);

CREATE TABLE research_reports (
    report_id TEXT PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES research_jobs(job_id),
    ticker TEXT NOT NULL REFERENCES companies(ticker),
    status TEXT NOT NULL,
    result_json TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX ix_reports_ticker_created ON research_reports(ticker, created_at);

CREATE TABLE forecast_cache (
    cache_key TEXT PRIMARY KEY,
    ticker TEXT NOT NULL REFERENCES companies(ticker),
    source_fingerprint TEXT NOT NULL,
    model_config_json TEXT NOT NULL,
    result_json TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE ai_runs (
    run_id TEXT PRIMARY KEY,
    job_id TEXT REFERENCES research_jobs(job_id),
    ticker TEXT,
    trace_id TEXT NOT NULL,
    status TEXT NOT NULL,
    started_at TEXT NOT NULL,
    completed_at TEXT,
    duration_ms DOUBLE PRECISION,
    error_category TEXT
);

CREATE TABLE ai_trace_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES ai_runs(run_id),
    trace_id TEXT NOT NULL,
    span_id TEXT,
    parent_span_id TEXT,
    stage TEXT NOT NULL,
    event_name TEXT NOT NULL,
    status TEXT NOT NULL,
    started_at TEXT NOT NULL,
    completed_at TEXT,
    duration_ms DOUBLE PRECISION,
    provider TEXT,
    model TEXT,
    input_tokens BIGINT,
    output_tokens BIGINT,
    retry_count BIGINT,
    error_category TEXT,
    metadata_json TEXT
);
CREATE INDEX ix_trace_run ON ai_trace_events(run_id, started_at);
CREATE INDEX ix_trace_stage ON ai_trace_events(stage, started_at);

CREATE TABLE observability_alerts (
    alert_id TEXT PRIMARY KEY,
    run_id TEXT REFERENCES ai_runs(run_id),
    severity TEXT NOT NULL,
    category TEXT NOT NULL,
    message TEXT NOT NULL,
    triggered_at TEXT NOT NULL,
    resolved_at TEXT
);

-- Version table of the original SQLite schema (kept as data).
CREATE TABLE schema_migrations (
    version BIGINT PRIMARY KEY,
    applied_at TEXT NOT NULL
);

CREATE TABLE market_companies (
    symbol TEXT PRIMARY KEY REFERENCES companies(ticker),
    market TEXT NOT NULL CHECK (market IN ('US', 'IN')),
    name TEXT NOT NULL,
    exchange TEXT,
    currency TEXT,
    sector_key TEXT,
    provider_sector TEXT,
    provider_industry TEXT,
    cik TEXT,
    in_universe BIGINT NOT NULL DEFAULT 0,
    profile_provider TEXT,
    profile_json TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    last_refreshed_at TEXT
);
CREATE INDEX ix_market_companies_market_sector ON market_companies(market, sector_key);

CREATE TABLE market_quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL REFERENCES companies(ticker),
    provider TEXT NOT NULL,
    currency TEXT,
    price TEXT,
    market_cap TEXT,
    pe_ratio TEXT,
    pb_ratio TEXT,
    dividend_yield_pct TEXT,
    beta TEXT,
    source_fields_json TEXT,
    as_of TEXT,
    fetched_at TEXT NOT NULL
);
CREATE INDEX ix_market_quotes_symbol ON market_quotes(symbol, fetched_at);

CREATE TABLE market_statements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL REFERENCES companies(ticker),
    provider TEXT NOT NULL,
    statement TEXT NOT NULL,
    period_type TEXT NOT NULL CHECK (period_type IN ('annual', 'quarterly')),
    period_end TEXT NOT NULL,
    fiscal_year TEXT,
    metric TEXT NOT NULL,
    value_text TEXT NOT NULL,
    currency TEXT,
    source_field TEXT,
    fetched_at TEXT NOT NULL,
    UNIQUE (symbol, provider, period_type, period_end, metric, value_text)
);
CREATE INDEX ix_market_statements_symbol ON market_statements(symbol, period_type, period_end);

CREATE TABLE provider_usage (
    provider TEXT NOT NULL,
    usage_day TEXT NOT NULL,
    requests BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (provider, usage_day)
);

CREATE TABLE research_execution_migrations (
    version BIGINT PRIMARY KEY,
    applied_at_utc TEXT NOT NULL
);

CREATE TABLE research_execution_runs (
    run_id TEXT PRIMARY KEY,
    ticker TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('queued', 'running', 'completed', 'failed')),
    created_at_utc TEXT NOT NULL,
    updated_at_utc TEXT NOT NULL,
    started_at_utc TEXT,
    finished_at_utc TEXT,
    agent_statuses_json TEXT NOT NULL,
    report_path TEXT,
    error_type TEXT,
    error_code TEXT
);
CREATE INDEX ix_research_execution_runs_ticker ON research_execution_runs(ticker, created_at_utc);

CREATE TABLE observability_schema_migrations (
    version BIGINT PRIMARY KEY,
    applied_at_utc TEXT NOT NULL
);

CREATE TABLE research_observability_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    trace_id TEXT NOT NULL,
    span_id TEXT NOT NULL,
    parent_span_id TEXT,
    component TEXT NOT NULL,
    step_name TEXT NOT NULL,
    event_type TEXT NOT NULL,
    status TEXT NOT NULL,
    duration_ms DOUBLE PRECISION NOT NULL,
    timestamp_utc TEXT NOT NULL,
    metadata_json TEXT NOT NULL
);
CREATE INDEX idx_research_observability_run ON research_observability_events(run_id, id);
CREATE INDEX idx_research_observability_trace ON research_observability_events(trace_id, id);

CREATE TABLE reliability_monitor_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluated_at_utc TEXT NOT NULL,
    sample_limit BIGINT NOT NULL,
    status TEXT NOT NULL,
    result_json TEXT NOT NULL
);

CREATE TABLE sec_company_validation (
    ticker TEXT PRIMARY KEY,
    cik TEXT,
    status TEXT NOT NULL CHECK (status IN ('validated', 'unavailable')),
    reason TEXT,
    revenue_quarters BIGINT,
    ocf_quarters BIGINT,
    latest_period_end TEXT,
    diagnostics_count BIGINT,
    checked_at TEXT NOT NULL
);
